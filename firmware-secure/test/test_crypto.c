/* Host test: AES-128 FIPS-197 vector + AES-CMAC RFC 4493 vectors. */
#include <stdio.h>
#include <string.h>
#include "../common/crypto.h"

static int hexeq(const uint8_t *a, const char *hex)
{
    for (int i = 0; i < 16; i++) {
        unsigned v; sscanf(hex + 2 * i, "%2x", &v);
        if (a[i] != v) return 0;
    }
    return 1;
}

int main(void)
{
    int fails = 0;
    const uint8_t k1[16] = {0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f};
    const uint8_t p1[16] = {0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff};
    uint8_t o[16];
    aes128_encrypt(k1, p1, o);
    if (!hexeq(o, "69c4e0d86a7b0430d8cdb78070b4c55a")) { puts("FAIL aes fips197"); fails++; }

    const uint8_t k[16] = {0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c};
    const uint8_t m[64] = {
        0x6b,0xc1,0xbe,0xe2,0x2e,0x40,0x9f,0x96,0xe9,0x3d,0x7e,0x11,0x73,0x93,0x17,0x2a,
        0xae,0x2d,0x8a,0x57,0x1e,0x03,0xac,0x9c,0x9e,0xb7,0x6f,0xac,0x45,0xaf,0x8e,0x51,
        0x30,0xc8,0x1c,0x46,0xa3,0x5c,0xe4,0x11,0xe5,0xfb,0xc1,0x19,0x1a,0x0a,0x52,0xef,
        0xf6,0x9f,0x24,0x45,0xdf,0x4f,0x9b,0x17,0xad,0x2b,0x41,0x7b,0xe6,0x6c,0x37,0x10};
    struct { size_t len; const char *mac; } v[] = {
        {0,  "bb1d6929e95937287fa37d129b756746"},
        {16, "070a16b46b4d4144f79bdd9dd04a287c"},
        {40, "dfa66747de9ae63030ca32611497c827"},
        {64, "51f0bebf7e3b9d92fc49741779363cfe"},
    };
    for (int i = 0; i < 4; i++) {
        aes_cmac(k, m, v[i].len, o);
        if (!hexeq(o, v[i].mac)) { printf("FAIL cmac len %zu\n", v[i].len); fails++; }
    }
    puts(fails ? "CRYPTO TESTS FAILED" : "crypto: all 5 vectors OK");
    return fails;
}
